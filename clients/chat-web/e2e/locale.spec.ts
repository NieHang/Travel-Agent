import { test, expect } from '@playwright/test'
import { PASSWORD, uniqueEmail } from './helpers'

test('语言切换、刷新保持，以及登录后采用账号语言', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Where to next?' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Where to next?' })).toBeVisible()
  await page.goto('/register')
  const email = uniqueEmail()
  await page.getByLabel('Nickname', { exact: true }).fill('Ann')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/chat$/)
  await page.getByRole('button', { name: 'Account menu' }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page).toHaveURL(/localhost:3102\/$/)
  await page.getByRole('button', { name: '中', exact: true }).click()
  await page.getByRole('link', { name: '登录', exact: true }).click()
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Hi Ann, where to?' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
})
test('浏览器首次使用英文时展示英文', async ({ browser }) => {
  const context = await browser.newContext({ locale: 'en-US' })
  const page = await context.newPage()
  await page.goto('http://localhost:3102')
  await expect(page.getByRole('heading', { name: 'Where to next?' })).toBeVisible()
  await context.close()
})
